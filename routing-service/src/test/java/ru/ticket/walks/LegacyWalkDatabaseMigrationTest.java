package ru.ticket.walks;

import java.nio.file.Path;
import java.sql.DriverManager;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import ru.ticket.walks.infrastructure.persistence.LegacyWalkDatabaseMigration;
import static org.junit.jupiter.api.Assertions.*;

class LegacyWalkDatabaseMigrationTest {
    @TempDir Path directory;

    @Test void copiesOnlyWalkCatalogsWithGeometryAndKeepsLegacyData() throws Exception {
        var legacy = directory.resolve("documents");
        var walks = directory.resolve("walks");
        try (var db = DriverManager.getConnection("jdbc:h2:file:" + legacy, "sa", "");
             var sql = db.createStatement()) {
            sql.execute("CREATE TABLE templates(id INT)");
            sql.execute("CREATE TABLE building_history(id BIGINT GENERATED BY DEFAULT AS IDENTITY, geometry GEOMETRY)");
            sql.execute("INSERT INTO building_history VALUES (DEFAULT, 'SRID=4326;POINT (30 59)')");
        }
        LegacyWalkDatabaseMigration.transfer(legacy, walks, "sa", "");
        LegacyWalkDatabaseMigration.transfer(legacy, walks, "sa", "");
        try (var db = DriverManager.getConnection("jdbc:h2:file:" + walks, "sa", "");
             var sql = db.createStatement();
             var data = sql.executeQuery("SELECT id, geometry FROM routing.building_history")) {
            assertTrue(data.next());
            assertEquals(1, data.getLong(1));
            assertEquals("SRID=4326;POINT (30 59)", data.getString(2));
            assertFalse(data.next());
            assertThrows(java.sql.SQLException.class, () -> sql.executeQuery("SELECT * FROM public.templates"));
        }
        try (var db = DriverManager.getConnection("jdbc:h2:file:" + legacy, "sa", "");
             var sql = db.createStatement();
             var data = sql.executeQuery("SELECT COUNT(*) FROM public.building_history")) {
            assertTrue(data.next());
            assertEquals(1, data.getLong(1));
        }
    }
}
